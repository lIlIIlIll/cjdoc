def first(manifest: dict, feature_id: str, locale: str) -> dict:
    matches = [target for feature in manifest["features"] if feature["id"] == feature_id
               for target in feature["targets"] if target["locale"] == locale and target["resolved"]]
    if not matches:
        raise ContractError("required primary showcase target is unavailable")
    return matches[0]


def cards(manifest: dict, locale: str | None = None) -> str:
    locale = locale or "zh-CN"
    language = 0 if locale == "zh-CN" else 1
    out = []
    features = {feature["id"]: feature for feature in manifest["features"]}
    grouped = {identity for _, _, _, identities in GROUPS for identity in identities}
    if set(features) - grouped:
        raise ContractError("feature has no reader task group: " + ', '.join(sorted(set(features) - grouped)))
    for group, chinese, english, identities in GROUPS:
        out.append(f'<section class="feature-group" aria-labelledby="task-{group}"><h3 id="task-{group}">{chinese if language == 0 else english}</h3><div class="feature-list">')
        for identity in identities:
            if identity in features:
                out.append(card(features[identity], locale))
        out.append('</div></section>')
    manifest_label = '完整功能清单与验证入口' if language == 0 else 'Full feature manifest and evidence routes'
    out.append(f'<p class="feature-manifest"><a class="link-external" href="showcase-features.json">{manifest_label}</a></p>')
    return '\n'.join(out)


def card(feature: dict, locale: str) -> str:
    language = 0 if locale == "zh-CN" else 1
    e = html.escape
    task = TASKS[feature["id"]]
    states = STATES[locale]
    title = feature["title"].split(" / ")
    card = (f'<article class="feature-card" data-feature-id="{e(feature["id"])}"'
            f' data-implementation="{e(feature["implementation"])}" data-demonstration="{e(feature["demonstration"])}">'
            f'<div class="feature-card__text"><h4>{e(title[min(language, len(title) - 1)])}</h4><p>{e(task[language + 2])}</p>')
    if feature["id"] in LIMITS:
        card += f'<p class="feature-limit"><strong>{"边界" if language == 0 else "Limit"}</strong> {e(LIMITS[feature["id"]][language])}</p>'
    targets = [target for target in feature["targets"] if target["locale"] == locale]
    resolved = [target for target in targets if target["resolved"]]
    if resolved:
        card += '<p class="feature-targets">'
        if len(targets) > 1:
            card += f'<span class="feature-targets__action">{e(task[language])}</span>'
        for target in resolved:
            attributes = f'data-target-id="{e(target["id"])}" lang="{e(target["locale"])}" href="{e(target["resolved"]["href"])}"'
            if len(targets) > 1:
                signature = target.get("signature") or target.get("match", {}).get("title", target["id"])
                card += (f'<a class="feature-target feature-target--versioned" {attributes}>'
                         f'<span class="feature-target__version">{e(target["version"])}</span> <code>{e(signature)}</code></a>')
            else:
                card += f'<a class="feature-target link-arrow" {attributes}>{e(task[language])}</a>'
        card += '</p>'
    card += (f'</div><p class="feature-status"><span class="feature-status__implementation">{e(states[feature["implementation"]])}</span>'
             f'<span class="feature-status__demonstration">{e(states[feature["demonstration"]])}</span></p></article>')
    return card


def publish(repo: Path, site: Path, manifest: dict, metadata: dict) -> None:
    template = (repo / "site/index.html").read_text(encoding="utf-8")
    mark_path = repo / "docs/assets/brand/mark.svg"
    if any(path.is_symlink() for path in (repo / "docs", repo / "docs/assets",
                                           repo / "docs/assets/brand", mark_path)) or not mark_path.is_file():
        raise ContractError("missing or unsafe showcase brand mark: docs/assets/brand/mark.svg")
    mark_svg = mark_path.read_text(encoding="utf-8").strip()
    if not mark_svg.startswith("<svg ") or mark_svg.count("<svg") != 1:
        raise ContractError("showcase brand mark must contain exactly one SVG root")
    inline_mark = mark_svg.replace("<svg ", '<svg aria-hidden="true" focusable="false" ', 1)
    if template.count('<!-- SHOWCASE_FEATURES -->') != 1:
        raise ContractError("homepage needs exactly one feature-catalog slot")
    if template.count('<!-- CJDOC_BRAND_MARK -->') != 1:
        raise ContractError("homepage needs exactly one CJDOC_BRAND_MARK slot")
    documentation_root = metadata["source"]["repository"] + '/blob/' + manifest["revision"] + '/docs/'
    for locale, filename in (("zh-CN", "index.html"), ("en", "en.html")):
        # The specimen frame and the primary action open the same native page.
        specimen = first(manifest, "search-discovery", locale)
        values = {**TEXT[locale], **UI_TEXT[locale], "LOCALE": locale, "REPOSITORY": metadata["source"]["repository"],
                  "GUIDE": first(manifest, "guide-association", locale)["resolved"]["href"],
                  "API_PAGE": specimen["resolved"]["href"],
                  "SPECIMEN_VERSION": specimen.get("version", ""),
                  "DIFF_TARGET": first(manifest, "api-diff", locale)["resolved"]["href"],
                  "CHECK_TARGET": first(manifest, "native-example-checks", locale)["resolved"]["href"],
                  "QUALITY_TARGET": first(manifest, "quality", locale)["resolved"]["href"],
                  "SOURCE": metadata["source"]["repository"] + '/tree/' + manifest["revision"] + '/examples/pocketkit',
                  "INSTALL_URL": documentation_root + "getting-started/install.md",
                  "FIRST_SITE_URL": documentation_root + "tutorials/first-site.md",
                  "HOW_TO_URL": documentation_root + "how-to/generate-and-publish.md",
                  "CONFIG_URL": documentation_root + "reference/configuration.md",
                  "DOCS_URL": documentation_root + "README.md",
                  "BUILD": json.dumps(metadata, ensure_ascii=False, indent=2)}
        content = template
        for key, value in values.items():
            content = content.replace('__' + key + '__', html.escape(value, quote=True))
        content = content.replace('<!-- SHOWCASE_FEATURES -->', cards(manifest, locale))
        content = content.replace('<!-- CJDOC_BRAND_MARK -->', inline_mark)
        content = content.replace('<!-- SHOWCASE_COVERAGE -->', coverage(manifest, locale))
        (site / filename).write_text(content, encoding="utf-8")


def coverage(manifest: dict, locale: str) -> str:
    """Describe demonstrated samples separately from planned capabilities."""
    features = manifest["features"]
    implemented = [feature for feature in features if feature["implementation"] != "not-implemented"]
    available = [feature for feature in implemented if feature["demonstration"] == "available"]
    partial = sum(feature["implementation"] == "partial" for feature in features)
    planned = sum(feature["implementation"] == "not-implemented" for feature in features)
    if locale == "zh-CN":
        text = (f"已实现的 {len(implemented)} 项能力中，{len(available)} 项可在本站直接试用；"
                f"其中 {partial} 项为部分实现，并写明了边界。另有 {planned} 项尚未实现。")
    else:
        text = (f"{len(available)} of {len(implemented)} implemented capabilities can be tried on this site; "
                f"{partial} are partial and state their limits. {planned} are not implemented yet.")
    return '<p class="coverage-summary" data-showcase-coverage>' + html.escape(text) + '</p>'


