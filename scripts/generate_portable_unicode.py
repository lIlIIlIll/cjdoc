#!/usr/bin/env python3
"""Emit Cangjie tables for portable filename comparison (Unicode 16.0.0)."""

import unicodedata as ucd


def main() -> None:
    if ucd.unidata_version != "16.0.0":
        raise SystemExit("regenerate with a Python interpreter using Unicode 16.0.0")
    decompositions = []
    classes = []
    for scalar in range(0x80, 0x110000):
        rune = chr(scalar)
        rank = ucd.combining(rune)
        if rank:
            classes.append(f"{scalar:06x}{rank:06x}")
        # The renderer decomposes modern Hangul syllables algorithmically.
        if 0xAC00 <= scalar < 0xD7A4:
            continue
        form = ucd.normalize("NFD", rune)
        if form == rune:
            continue
        parts = [ord(part) for part in form]
        if len(parts) > 4:
            raise SystemExit(f"U+{scalar:04X} needs a wider decomposition record")
        parts.extend([0] * (4 - len(parts)))
        decompositions.append("".join(f"{value:06x}" for value in [scalar, *parts]))
    print("package cjdoc.render\n")
    print("// Generated by scripts/generate_portable_unicode.py from Unicode 16.0.0.")
    print("// Sorted fixed-width records of six-digit ASCII hexadecimal fields.")
    print(f'internal let PORTABLE_UNICODE_DECOMPOSITIONS = "{"".join(decompositions)}"')
    print(f'internal let PORTABLE_UNICODE_COMBINING_CLASSES = "{"".join(classes)}"')


if __name__ == "__main__":
    main()
