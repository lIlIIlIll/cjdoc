def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def write_json(path: Path, value: object) -> Path:
    return write(path, json.dumps(value, ensure_ascii=False))


def make_site(root: Path, language: str | None = "en", *, pages: int = 2) -> Path:
    """Build one captured site with the artifacts the baseline server serves."""
    site = root / "site" if language is None else root / "site" / language
    site.mkdir(parents=True, exist_ok=True)
    navigation_pages = []
    for index in range(pages):
        href = f"symbols/page-{index}.html"
        write(site / href, f"<html><body>page {index} {language}</body></html>\n")
        navigation_pages.append({"id": f"sym:{index}", "kind": "symbol",
                                 "title": f"page {index}", "href": href,
                                 "summary": None, "symbolId": f"sym:{index}",
                                 "moduleId": "cjdoc:module:v1:root",
                                 "packageName": "demo", "semanticState": "resolved"})
    write_json(site / "navigation-index.json", {
        "schemaVersion": "cjdoc.navigation-index/1",
        "project": {"name": "demo", "audience": "external", "version": "1.2.3"},
        "pages": navigation_pages,
    })
    write_json(site / "symbol-index.json", {
        "schemaVersion": "cjdoc.symbol-index/2",
        "project": {"name": "demo", "audience": "external"},
        "version": "1.2.3",
        "entries": [], "dependencies": [],
        "documentSets": ([] if language is None else
                         [{"id": "set", "language": language}]),
    })
    write_json(site / "search-index.json", {
        "schemaVersion": "cjdoc.search-index/9",
        "entries": [{"id": "sym:0", "canonicalId": "cjdoc:v2:x", "exposure": True,
                     "name": "page", "qualifiedName": "demo.page", "kind": "function",
                     "packageName": "demo", "summary": "", "href": "symbols/page-0.html"}],
    })
    write(site / "llms.txt", "# demo\n\nGenerated by cjdoc.\n")
    write(site / "llms-full.txt", "# demo\n\n## Body\n\n完整正文 汉\n")
    write(site / "style.css", "body{}\n")
    write(site / "docs.json", "{}\n")
    write(site / "api-surface.json", "{}\n")
    (site / "markdown").mkdir()
    write(site / "markdown/index.md", "# demo\n")
    return root


def serve(site_root: Path, requests: list[dict], *,
          max_read_bytes: int | None = None) -> list[dict]:
    """Drive one real stdio session against the baseline server."""
    command = [sys.executable, str(SCRIPTS / "agent_baseline_mcp.py"),
               "--baseline", str(site_root)]
    if max_read_bytes is not None:
        command.extend(["--max-read-bytes", str(max_read_bytes)])
    payload = "".join(json.dumps(request) + "\n" for request in requests)
    result = subprocess.run(command, input=payload.encode("utf-8"),
                            capture_output=True, timeout=120)
    if result.returncode != 0:
        raise AssertionError(result.stderr.decode("utf-8", "replace"))
    return [json.loads(line) for line in result.stdout.decode("utf-8").splitlines()]


def call(identifier: int, name: str, arguments: dict) -> dict:
    return {"jsonrpc": "2.0", "id": identifier, "method": "tools/call",
            "params": {"name": name, "arguments": arguments}}


INITIALIZE = {"jsonrpc": "2.0", "id": 0, "method": "initialize",
              "params": {"protocolVersion": "2025-11-25", "capabilities": {},
                         "clientInfo": {"name": "test", "version": "1"}}}
INITIALIZED = {"jsonrpc": "2.0", "method": "notifications/initialized"}
TOOLS_LIST = {"jsonrpc": "2.0", "id": 1, "method": "tools/list"}


def payload(response: dict) -> dict:
    result = response["result"]
    return json.loads(result["content"][0]["text"])


class BaselineServerTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = make_site(Path(self.temporary.name))

    def test_lifecycle_lists_only_servable_documents(self):
        responses = serve(self.root, [INITIALIZE, INITIALIZED, TOOLS_LIST])
        self.assertEqual(responses[0]["result"]["protocolVersion"], "2025-11-25")
        names = [tool["name"] for tool in responses[1]["result"]["tools"]]
        self.assertEqual(names, ["list_documents", "read_document"])
        listed = payload(next(response for response in serve(
            self.root, [INITIALIZE, INITIALIZED,
                        call(2, "list_documents", {"limit": 100})])
            if response["id"] == 2))
        suffixes = {item["document"].rsplit("/", 1)[-1] for item in listed["documents"]}
        self.assertEqual(suffixes, {"llms.txt", "llms-full.txt", "navigation-index.json",
                                    "symbol-index.json", "search-index.json",
                                    "page-0.html", "page-1.html"})
        # Doc IR, api-surface and authoring sources are oracle material.
        for forbidden in ("docs.json", "api-surface.json", "style.css", "index.md"):
            self.assertNotIn(forbidden, suffixes)

    def test_listing_is_deterministic_and_paginates(self):
        first = serve(self.root, [INITIALIZE, INITIALIZED,
                                  call(2, "list_documents", {"limit": 3})])[-1]
        second = serve(self.root, [INITIALIZE, INITIALIZED,
                                   call(2, "list_documents", {"limit": 3})])[-1]
        self.assertEqual(payload(first), payload(second))
        page = payload(first)
        self.assertEqual((page["total"], page["returned"], page["hasMore"]), (7, 3, True))
        following = payload(serve(self.root, [INITIALIZE, INITIALIZED,
                                              call(2, "list_documents", {"offset": 3,
                                                                         "limit": 3})])[-1])
        self.assertEqual(following["offset"], 3)
        ids = [item["document"] for item in page["documents"] + following["documents"]]
        self.assertEqual(ids, sorted(ids))
        self.assertEqual(len(set(ids)), len(ids))

    def test_read_reports_scope_offsets_and_byte_boundaries(self):
        body = (self.root / "site/en/llms-full.txt").read_bytes()
        response = serve(self.root, [INITIALIZE, INITIALIZED, call(
            2, "read_document", {"document": "site/en/llms-full.txt",
                                 "offset": 0, "limit": len(body)})])[-1]
        page = payload(response)
        self.assertEqual(page["kind"], "llms")
        self.assertEqual(page["scope"]["project"], "demo")
        self.assertEqual(page["scope"]["version"], "1.2.3")
        self.assertEqual(page["scope"]["language"], "en")
        self.assertEqual(page["offset"], 0)
        self.assertEqual(page["endOffset"], len(body))
        self.assertFalse(page["hasMore"])
        self.assertEqual(page["returnedBytes"], len(body))
        self.assertIn("完整正文", page["text"])

        # A window that starts inside a multi-byte rune advances to that rune.
        start = body.index("汉".encode("utf-8"))
        window = payload(serve(self.root, [INITIALIZE, INITIALIZED, call(
            2, "read_document", {"document": "site/en/llms-full.txt",
                                 "offset": start + 1, "limit": 8})])[-1])
        self.assertEqual(window["utf8BoundaryAdjusted"], "start")
        self.assertEqual(window["offset"], start)
        self.assertEqual(window["requestedOffset"], start + 1)
        self.assertTrue(window["text"].startswith("汉"))
        # The window starts and stops on rune boundaries, so no partial character
        # is ever returned and the delivered byte count matches the text.
        self.assertEqual(window["returnedBytes"], len(window["text"].encode("utf-8")))
        self.assertEqual(window["endOffset"] - window["offset"], window["returnedBytes"])
        self.assertEqual(window["endOffset"] - start, 1 + len("汉".encode("utf-8")))

    def test_empty_site_reports_empty_rather_than_inventing_scope(self):
        empty = Path(self.temporary.name) / "empty"
        write_json(empty / "navigation-index.json",
                   {"schemaVersion": "cjdoc.navigation-index/1",
                    "project": {"name": "demo", "audience": "external", "version": None},
                    "pages": []})
        write(empty / "llms.txt", "")
        response = payload(serve(self.root, [INITIALIZE, INITIALIZED, call(
            2, "read_document", {"document": "empty/llms.txt",
                                 "limit": 10})], max_read_bytes=16)[-1])
        self.assertIsNone(response["scope"]["version"])
        self.assertIsNone(response["scope"]["language"])
        self.assertEqual(response["text"], "")
        self.assertEqual(response["returnedBytes"], 0)
        # The named empty site is discovered alongside the populated one.
        inventory = payload(serve(self.root, [INITIALIZE, INITIALIZED,
                                              call(2, "list_documents",
                                                   {"site": "empty"})])[-1])
        # The empty site publishes only its own index and the empty llms file.
        self.assertEqual(inventory["total"], 2)
        self.assertEqual([item["document"] for item in inventory["documents"]],
                         ["empty/llms.txt", "empty/navigation-index.json"])


class SiteAllowlistTests(unittest.TestCase):
    """Naming sites is how a run pins which captured documentation is reachable."""

    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = make_site(Path(self.temporary.name) / "capture")
        # A second, unrelated captured site must stay unreachable when not named.
        other = self.root / "other" / "zh-CN"
        other.mkdir(parents=True)
        write_json(other / "navigation-index.json", {
            "schemaVersion": "cjdoc.navigation-index/1",
            "project": {"name": "other", "audience": "external", "version": "9"},
            "pages": []})
        write(other / "llms.txt", "# other\n")

    def run_named(self, *sites: tuple[str, str]) -> list[dict]:
        command = [sys.executable, str(SCRIPTS / "agent_baseline_mcp.py"),
                   "--baseline", str(self.root)]
        for name, relative in sites:
            command.extend(["--site", f"{name}={self.root / relative}"])
        requests = [INITIALIZE, INITIALIZED,
                    call(2, "list_documents", {"limit": 100}),
                    call(3, "read_document", {"document": "other/zh-CN/llms.txt"})]
        payload_text = "".join(json.dumps(request) + "\n" for request in requests)
        result = subprocess.run(command, input=payload_text.encode("utf-8"),
                                capture_output=True, timeout=120)
        return [json.loads(line) for line in result.stdout.decode("utf-8").splitlines()]

    def test_only_named_sites_are_served(self):
        responses = self.run_named(("demo-en", "site/en"))
        listing = payload(responses[1])
        self.assertEqual([site["site"] for site in listing["sites"]], ["demo-en"])
        self.assertEqual({item["site"] for item in listing["documents"]}, {"demo-en"})
        refusal = responses[2]["result"]
        self.assertTrue(refusal["isError"])
        self.assertIn("unknown document", refusal["content"][0]["text"])

    def test_named_nested_site_is_not_duplicated_by_its_parent(self):
        inner = self.root / "site/en/dependencies/extra"
        write_json(inner / "navigation-index.json", {
            "schemaVersion": "cjdoc.navigation-index/1",
            "project": {"name": "extra", "audience": "external", "version": "1"},
            "pages": []})
        write(inner / "llms.txt", "# extra\n")
        responses = self.run_named(("parent", "site/en"),
                                   ("child", "site/en/dependencies/extra"))
        listing = payload(responses[1])
        self.assertEqual(sorted(site["site"] for site in listing["sites"]),
                         ["child", "parent"])
        parent_documents = [item for item in listing["documents"]
                            if item["site"] == "parent"]
        self.assertFalse([item for item in parent_documents
                          if "/dependencies/extra/" in item["document"]])

    def test_unnamed_or_escaping_sites_are_refused(self):
        command = [sys.executable, str(SCRIPTS / "agent_baseline_mcp.py"),
                   "--baseline", str(self.root), "--site",
                   f"escape={self.root.parent}"]
        result = subprocess.run(command, capture_output=True, timeout=120)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("escapes the baseline root", result.stderr.decode("utf-8"))


class ConfinementTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.base = Path(self.temporary.name)
        self.root = make_site(self.base / "capture")

    def _error_text(self, response: dict) -> str:
        self.assertTrue(response["result"].get("isError"))
        return json.loads(response["result"]["content"][0]["text"])["message"]

    def test_path_traversal_and_absolute_ids_are_refused(self):
        outside = write(self.base / "secret.txt", "do not read\n")
        for identifier in (str(outside), "../secret.txt", "site/en/../../secret.txt",
                           "site/en/docs.json", "site/../capture/site/en/llms.txt",
                           "/etc/passwd"):
            with self.subTest(document=identifier):
                response = serve(self.root, [INITIALIZE, INITIALIZED,
                                             call(2, "read_document",
                                                  {"document": identifier})])[-1]
                self.assertIn("unknown document", self._error_text(response))
        empty = serve(self.root, [INITIALIZE, INITIALIZED,
                                  call(2, "read_document", {"document": ""})])[-1]
        self.assertIn("non-empty document id", self._error_text(empty))

    def test_unlisted_but_present_files_stay_unreachable(self):
        # A file inside the tree that the server does not publish cannot be named.
        write(self.root / "site/en/oracle.json", '{"secret": true}\n')
        response = serve(self.root, [INITIALIZE, INITIALIZED, call(
            2, "read_document", {"document": "site/en/oracle.json"})])[-1]
        self.assertIn("unknown document", self._error_text(response))

    @unittest.skipUnless(hasattr(Path, "symlink_to"), "symlinks are unavailable")
    def test_symlinked_document_is_refused(self):
        outside = write(self.base / "outside.txt", "outside\n")
        link = self.root / "site/en/llms-extra.txt"
        try:
            link.symlink_to(outside)
        except OSError:
            self.skipTest("this platform cannot create symlinks")
        ok = serve(self.root, [INITIALIZE, INITIALIZED, call(
            2, "read_document", {"document": "site/en/llms.txt"})])[-1]
        self.assertFalse(ok["result"]["isError"])
        corpus = baseline.Corpus(baseline.scan_baseline(self.root))
        self.assertNotIn("site/en/llms-extra.txt", corpus.documents)

    def test_invalid_arguments_fail_with_a_message_not_a_crash(self):
        cases = [
            call(2, "read_document", {"document": "site/en/llms.txt", "offset": -1}),
            call(2, "read_document", {"document": "site/en/llms.txt", "limit": 0}),
            call(2, "read_document", {"document": "site/en/llms.txt",
                                     "limit": baseline.MAX_READ_BYTES + 1}),
            call(2, "read_document", {"document": "site/en/llms.txt", "offset": "0"}),
            call(2, "list_documents", {"kind": "docs-json"}),
            call(2, "list_documents", {"site": "missing-site"}),
            call(2, "list_documents", {"limit": baseline.MAX_LIST_LIMIT + 1}),
        ]
        for request in cases:
            with self.subTest(request=request["params"]):
                response = serve(self.root, [INITIALIZE, INITIALIZED, request])[-1]
                self.assertTrue(response["result"]["isError"])
                self.assertIn("message", json.loads(
                    response["result"]["content"][0]["text"]))
        unknown_tool = serve(self.root, [INITIALIZE, INITIALIZED, {
            "jsonrpc": "2.0", "id": 2, "method": "tools/call",
            "params": {"name": "read_source", "arguments": {}}}])[-1]
        self.assertEqual(unknown_tool["error"]["code"], -32602)
        self.assertIn("unknown tool", unknown_tool["error"]["message"])

    def test_windows_reconstruct_bytes_and_past_the_end_reports_the_end(self):
        target = "site/en/llms-full.txt"
        body = (self.root / target).read_bytes()
        rebuilt = bytearray()
        offset = 0
        for _ in range(len(body) + 1):
            page = payload(serve(self.root, [INITIALIZE, INITIALIZED, call(
                2, "read_document", {"document": target, "offset": offset,
                                    "limit": 3})])[-1])
            self.assertGreaterEqual(page["endOffset"], offset)
            self.assertEqual(page["returnedBytes"], len(page["text"].encode("utf-8")))
            rebuilt += page["text"].encode("utf-8")
            offset = page["endOffset"]
            if not page["hasMore"]:
                break
        self.assertEqual(bytes(rebuilt), body)
        past = payload(serve(self.root, [INITIALIZE, INITIALIZED, call(
            2, "read_document", {"document": target, "offset": len(body) + 1000,
                                 "limit": 8})])[-1])
        self.assertEqual((past["offset"], past["endOffset"], past["hasMore"]),
                         (len(body), len(body), False))
        self.assertEqual(past["text"], "")

    def test_invalid_utf8_is_reported_rather_than_replaced(self):
        broken = self.root / "site/en/llms-full.txt"
        broken.write_bytes(b"# ok\n\xff\xfe broken\n")
        response = payload(serve(self.root, [INITIALIZE, INITIALIZED, call(
            2, "read_document", {"document": "site/en/llms-full.txt",
                                 "offset": 0, "limit": 32})])[-1])
        self.assertTrue(response["invalidUtf8"])
        self.assertNotIn("\ufffd", response["text"])

    def test_tool_calls_before_initialize_are_refused(self):
        response = serve(self.root, [TOOLS_LIST])[0]
        self.assertEqual(response["error"]["code"], -32002)

    def test_missing_navigation_index_is_a_startup_error(self):
        empty = Path(self.temporary.name) / "not-a-site"
        write(empty / "llms.txt", "# nothing\n")
        result = subprocess.run([sys.executable, str(SCRIPTS / "agent_baseline_mcp.py"),
                                 "--baseline", str(empty)],
                                capture_output=True, timeout=120)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("navigation-index.json", result.stderr.decode("utf-8"))


class RelayBudgetTests(unittest.TestCase):
    """The relay is exercised against a real child process over real pipes."""

    SERVER = (
        "import json, sys\n"
        "for line in sys.stdin:\n"
        "    message = json.loads(line)\n"
        "    if 'id' not in message:\n"
        "        continue\n"
        "    if message['method'] == 'initialize':\n"
        "        result = {'protocolVersion': '2025-11-25', 'capabilities': {},\n"
        "                  'serverInfo': {'name': 'stub', 'version': '1'}}\n"
        "    elif message['method'] == 'tools/list':\n"
        "        result = {'tools': [{'name': 'read_document',\n"
        "                            'inputSchema': {'type': 'object'}}]}\n"
        "    else:\n"
        "        result = {'content': [{'type': 'text', 'text': 'x' * 800}]}\n"
        "    print(json.dumps({'jsonrpc': '2.0', 'id': message['id'], 'result': result}),\n"
        "          flush=True)\n"
    )

    def run_relay(self, requests: list[dict], *, calls: int, bytes_: int) -> tuple:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        log = Path(temporary.name)
        command = [sys.executable, str(SCRIPTS / "agent_evaluation.py"), "relay",
                   "--log", str(log), "--max-tool-calls", str(calls),
                   "--max-result-bytes", str(bytes_), "--cwd", str(log), "--",
                   sys.executable, "-c", self.SERVER]
        payload = "".join(json.dumps(request) + "\n" for request in requests)
        result = subprocess.run(command, input=payload.encode("utf-8"),
                                capture_output=True, timeout=120)
        self.assertEqual(result.returncode, 0, result.stderr.decode("utf-8", "replace"))
        responses = [json.loads(line) for line in result.stdout.decode("utf-8").splitlines()]
        transcript = [json.loads(line) for line in
                      (log / evaluation.RELAY_LOG_NAME).read_text(encoding="utf-8").splitlines()]
        return responses, transcript, evaluation.read_relay_log(log / evaluation.RELAY_LOG_NAME)

    def test_call_budget_refuses_and_is_recorded(self):
        requests = [INITIALIZE, INITIALIZED, TOOLS_LIST] + [
            call(index, "read_document", {}) for index in range(2, 6)]
        responses, transcript, summary = self.run_relay(requests, calls=2, bytes_=1 << 20)
        by_id = {response["id"]: response for response in responses}
        self.assertFalse(by_id[2]["result"].get("isError", False))
        self.assertFalse(by_id[3]["result"].get("isError", False))
        for identifier in (4, 5):
            self.assertTrue(by_id[identifier]["result"]["isError"])
        budget = next(item for item in transcript if item.get("kind") == "budget")
        self.assertEqual((budget["toolCalls"], budget["exceeded"]), (4, "toolCalls"))
        self.assertEqual(summary["toolCalls"], 4)
        # Every over-budget attempt is refused and recorded once, so the client
        # cannot retry its way past the fixed limit.
        self.assertEqual(summary["budgetRefusals"], 2)
        self.assertEqual(summary["initialize"], 1)
        self.assertEqual(summary["toolsList"], 1)

    def test_byte_budget_counts_delivered_results_and_refuses_without_truncating(self):
        requests = [INITIALIZE, INITIALIZED] + [
            call(index, "read_document", {}) for index in range(2, 6)]
        responses, transcript, summary = self.run_relay(requests, calls=24, bytes_=900)
        by_id = {response["id"]: response for response in responses}
        # Only the first complete document fits; later calls receive measured
        # enforcement results, never fragments of the rejected document.
        self.assertFalse(by_id[2]["result"].get("isError", False))
        self.assertEqual(len(by_id[2]["result"]["content"][0]["text"]), 800)
        # The next result would cross the limit, so it is withheld rather than
        # delivered as a truncated document, and the budget fails the task.
        for identifier in (3, 4, 5):
            self.assertTrue(by_id[identifier]["result"].get("isError"))
        self.assertNotIn("xxx", by_id[3]["result"]["content"][0]["text"])
        budget = next(item for item in transcript if item.get("kind") == "budget")
        self.assertEqual(budget["exceeded"], "documentBytes")
        expected_bytes = len(json.dumps(by_id[2]["result"]).encode("utf-8"))
        expected_bytes += sum(len(json.dumps(by_id[index]["result"],
            ensure_ascii=False, separators=(",", ":")).encode("utf-8"))
            for index in (3, 4, 5))
        self.assertEqual(budget["resultBytes"], expected_bytes)
        self.assertEqual(summary["resultBytes"], budget["resultBytes"])
        self.assertEqual(summary["toolCalls"], 4)

    def test_read_cost_preserves_transmitted_unicode_escapes_and_spaces(self):
        self.SERVER = self.SERVER.replace("'x' * 800", "'汉' * 100")
        responses, _, summary = self.run_relay(
            [INITIALIZE, INITIALIZED, call(2, "read_document", {})],
            calls=24, bytes_=10000)
        result = next(response["result"] for response in responses if response["id"] == 2)
        self.assertEqual(result["content"][0]["text"], "汉" * 100)
        self.assertEqual(summary["resultBytes"],
                         len(json.dumps(result).encode("utf-8")))

    def test_transcript_keeps_every_line_verbatim(self):
        requests = [INITIALIZE, INITIALIZED, TOOLS_LIST,
                    call(2, "read_document", {"document": "a"})]
        responses, transcript, _ = self.run_relay(requests, calls=24, bytes_=1 << 20)
        relayed = [item["line"] for item in transcript
                   if item.get("direction") == "server->client"]
        self.assertEqual(len(relayed), len(responses))
        replayed = [json.loads(line) for line in relayed]
        self.assertEqual([item["id"] for item in replayed], [0, 1, 2])
        calls = [item for item in transcript
                 if item.get("direction") == "client->server"
                 and item.get("method") == "tools/call"]
        self.assertEqual(len(calls), 1)
